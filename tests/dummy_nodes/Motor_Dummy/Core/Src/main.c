/**
  * @brief  This function is executed in case of error occurrence.
  * @retval None
  */
void Error_Handler(void)
{
  /* [2026-08-30] 원래는 __disable_irq() 후 빈 while(1) 이었다. 그 상태로는
     보드가 죽었는지 그냥 조용한 건지 밖에서 구분할 방법이 전혀 없어서,
     HSE 설정 오류로 세 보드가 모두 멈춰 있는 걸 알아채는 데 오래 걸렸다.
     LD2(PA5)를 빠르게 깜빡여 "펌웨어가 죽었다"를 눈으로 알 수 있게 한다.

     클럭 설정 실패 시점에도 동작해야 하므로 HAL 을 쓰지 않고 레지스터를
     직접 건드린다. 이때 SYSCLK 는 HSI 16 MHz 이므로 아래 지연 상수는
     대략 0.1 초다(정확할 필요 없음). */
  __disable_irq();

  RCC->AHB1ENR |= RCC_AHB1ENR_GPIOAEN;
  (void)RCC->AHB1ENR;                 /* 클럭 인가 반영 대기 */
  GPIOA->MODER   = (GPIOA->MODER & ~(3UL << (5 * 2))) | (1UL << (5 * 2));
  GPIOA->OTYPER &= ~(1UL << 5);

  while (1)
  {
    GPIOA->ODR ^= (1UL << 5);
    for (volatile uint32_t i = 0; i < 200000UL; i++) { __NOP(); }
  }
}

/* [DMA 버퍼 & 전역 변수] */
/* GPDMA가 백그라운드에서 이 배열에 데이터를 계속 채워줍니다. */
uint32_t adc_ain_value[2];  // ADC4: [0] PC1, [1] PC2
uint32_t adc_sys_value[2];  // ADC1: [0] CPU 온도(Raw), [1] VSENSE(PB1)

/* 메인 루프와 통신하기 위한 플래그 (main.c에 정의됨) */
extern volatile uint32_t adc_flag;

/* [인터럽트 콜백 함수]
 * DMA 전송(변환)이 완료되면 호출됩니다.
 */
void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef* hadc) {

  // 1. ADC1 (시스템 센서: CPU 온도, 전압) 처리
  if (hadc->Instance == ADC1) {
    /* [F시리즈 호환성 보완]
     * F시리즈 코드: (... + 30) * 10; -> 섭씨 30.5도를 305로 표현
     * U시리즈 매크로: 정수형 섭씨 반환 (예: 30)
     * -> 기존 포맷을 맞추기 위해 결과값에 10을 곱해서 저장합니다.
     */
    int32_t temperature_C = __HAL_ADC_CALC_TEMPERATURE(hadc1.Instance, 3300, adc_sys_value[0], ADC_RESOLUTION_14B);
    adc_sys_value[0] = (uint32_t)(temperature_C * 10); // *10 스케일링 적용

    // 플래그 설정 (Main Loop에 알림)
    adc_flag |= (1 << FLAG_ADC_SYS);
  }

  // 2. ADC4 (외부 센서: PC1, PC2) 처리
  else if (hadc->Instance == ADC4) {
    // 외부 센서는 Raw 값을 그대로 사용하거나 필요시 여기서 변환 식 추가
    // 플래그 설정
    adc_flag |= (1 << FLAG_ADC_AIN);
  }
}
